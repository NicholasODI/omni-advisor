import assert from 'node:assert/strict';
import { PlanningGate } from './planningGate.ts';
import extension from './index.ts';
const gate = new PlanningGate();
gate.begin('a');
for (const tool of ['read', 'grep', 'glob', 'ls', 'find', 'ask_advisor', 'register_masked_terms']) assert.equal(gate.blocked('a', tool), false);
for (const tool of ['bash', 'write', 'edit', 'task', 'custom_mutator']) assert.equal(gate.blocked('a', tool), true);
const old = gate.token('a'); gate.begin('a'); gate.complete('a', old);
assert.equal(gate.blocked('a', 'bash'), true);
gate.complete('a', gate.token('a'));
assert.equal(gate.blocked('a', 'bash'), false);
assert.equal(gate.blocked('b', 'bash'), true);
gate.begin('a'); assert.equal(gate.blocked('a', 'write'), true);
const hooks: Record<string, any> = {}; const commands: Record<string, any> = {}; const tools: Record<string, any> = {};
const schema: any = new Proxy(() => schema, { get: () => schema, apply: () => schema });
extension({ zod: schema, registerTool: (t: any) => tools[t.name] = t, registerCommand: (name: string, t: any) => commands[name] = t,
  on: (name: string, fn: any) => hooks[name] = fn } as any);
const ctx: any = { sessionManager: { getSessionFile: () => '/test/enforced-planning' }, ui: { notify: () => {} } };
assert.equal(await hooks.tool_call({ toolName: 'bash' }, ctx), undefined);
await commands['omni-advisor'].handler('planning on', ctx);
const start = await hooks.before_agent_start({ reason: 'prompt', systemPrompt: ['base'] }, ctx);
assert.match(start.systemPrompt.join('\n'), /ENFORCED PLANNING/);
assert.equal((await hooks.tool_call({ toolName: 'bash' }, ctx)).block, true);
assert.equal(await hooks.tool_call({ toolName: 'read' }, ctx), undefined);
const disabled = await tools.ask_advisor.execute('', { objective: 'Plan worker', questions: 'Invariants?' }, undefined, undefined, ctx);
assert.match(disabled.content[0].text, /blocked/);
assert.equal((await hooks.tool_call({ toolName: 'write' }, ctx)).block, true);
await commands['omni-advisor'].handler('planning off', ctx);
assert.equal(await hooks.tool_call({ toolName: 'write' }, ctx), undefined);
console.log('Planning gate tests passed: discovery, execution blocking, stale results, isolation, per-prompt reset, disabled cloud, explicit opt-out.');
